/*
  Phish Radar AI - MySQL/MariaDB users
  PasswordHash stores an Argon2 hash. No plaintext password column is allowed.
*/

CREATE TABLE IF NOT EXISTS `Users`
(
    `UserId` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `Username` VARCHAR(50) NOT NULL,
    `NormalizedUsername` VARCHAR(50)
        GENERATED ALWAYS AS (LOWER(TRIM(`Username`))) STORED,
    `PasswordHash` VARCHAR(255) NOT NULL,
    `Email` VARCHAR(254) NOT NULL,
    `NormalizedEmail` VARCHAR(254)
        GENERATED ALWAYS AS (LOWER(TRIM(`Email`))) STORED,
    `Role` ENUM('user', 'admin') NOT NULL DEFAULT 'user',
    `IsActive` BOOLEAN NOT NULL DEFAULT TRUE,
    `EmailVerified` BOOLEAN NOT NULL DEFAULT FALSE,
    `CreatedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    `UpdatedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
        ON UPDATE CURRENT_TIMESTAMP(3),
    `LastLoginAt` DATETIME(3) NULL,

    CONSTRAINT `PK_Users` PRIMARY KEY (`UserId`),
    CONSTRAINT `UX_Users_NormalizedUsername` UNIQUE (`NormalizedUsername`),
    CONSTRAINT `UX_Users_NormalizedEmail` UNIQUE (`NormalizedEmail`)
) ENGINE=InnoDB
  DEFAULT CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

/*
  Phish Radar AI - server-side authentication sessions
  Session tokens are generated by the Backend. Only their SHA-256 hashes are
  stored in TokenHash.

  Shared-hosting compatible: relationships are indexed but FOREIGN KEY and
  CHECK clauses are intentionally omitted when REFERENCES is unavailable.
*/

CREATE TABLE IF NOT EXISTS `Sessions`
(
    `SessionId` CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    `UserId` BIGINT UNSIGNED NOT NULL,
    `TokenHash` BINARY(32) NOT NULL,
    `CreatedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    `LastSeenAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    `ExpiresAt` DATETIME(3) NOT NULL,
    `RevokedAt` DATETIME(3) NULL,

    CONSTRAINT `PK_Sessions` PRIMARY KEY (`SessionId`),
    CONSTRAINT `UX_Sessions_TokenHash` UNIQUE (`TokenHash`),
    INDEX `IX_Sessions_User_ExpiresAt` (`UserId`, `ExpiresAt`)
) ENGINE=InnoDB
  DEFAULT CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

/*
  Phish Radar AI - sanitized URL history and Risk Model audit data

  Url never stores credentials, query strings or fragments. LayerResults is
  serialized JSON from the Backend and is stored as LONGTEXT for broad
  MySQL/MariaDB hosting compatibility.

  Shared-hosting compatible: UserId remains an indexed logical
  relationships, without FOREIGN KEY or CHECK clauses that require privileges
  or parser support not provided by some hosting plans.
*/

CREATE TABLE IF NOT EXISTS `SearchHistory`
(
    `HistoryId` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `UserId` BIGINT UNSIGNED NOT NULL,
    `Url` VARCHAR(2048) NOT NULL,
    `UrlHash` BINARY(32) NOT NULL,
    `Hostname` VARCHAR(253) NOT NULL,
    `RuleScore` TINYINT UNSIGNED NOT NULL,
    `MlScore` TINYINT UNSIGNED NULL,
    `FinalScore` TINYINT UNSIGNED NOT NULL,
    `Alpha` DECIMAL(5, 4) NULL,
    `DecisionThreshold` DECIMAL(6, 2) NULL,
    `DetectionLabel` ENUM('safe', 'phishing') NULL,
    `ModelStatus` VARCHAR(50) NULL,
    `Source` ENUM('web-app', 'qr-scanner') NOT NULL DEFAULT 'web-app',
    `RiskProbability` DECIMAL(9, 8) NULL,
    `RiskScore` TINYINT UNSIGNED NULL,
    `Decision` ENUM('allow', 'warn', 'block') NULL,
    `WarningThreshold` DECIMAL(6, 2) NULL,
    `BlockingThreshold` DECIMAL(6, 2) NULL,
    `ModelVersion` VARCHAR(100) NULL,
    `PolicyVersion` VARCHAR(100) NULL,
    `FeatureSchemaVersion` VARCHAR(100) NULL,
    `LayerResults` LONGTEXT NULL,
    `CreatedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),

    CONSTRAINT `PK_SearchHistory` PRIMARY KEY (`HistoryId`),
    INDEX `IX_SearchHistory_User_CreatedAt` (`UserId`, `CreatedAt`, `HistoryId`)
) ENGINE=InnoDB
  DEFAULT CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `ScanFeedback` (
    `FeedbackId` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    `HistoryId` BIGINT UNSIGNED NOT NULL,
    `UserId` BIGINT UNSIGNED NOT NULL,
    `UserLabel` ENUM('dangerous','safe','unsure') NOT NULL,
    `ReviewStatus` ENUM('pending','confirmed','dismissed') NOT NULL DEFAULT 'pending',
    `ReviewNote` VARCHAR(1000) NOT NULL DEFAULT '',
    `ReviewedBy` BIGINT UNSIGNED NULL,
    `ReviewedAt` DATETIME(3) NULL,
    `CreatedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    UNIQUE KEY `UX_Feedback_History_User` (`HistoryId`, `UserId`),
    INDEX `IX_Feedback_Review` (`ReviewStatus`, `CreatedAt`)
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `AuditEvents` (
    `AuditId` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    `ActorUserId` BIGINT UNSIGNED NOT NULL,
    `Action` VARCHAR(80) NOT NULL,
    `TargetType` VARCHAR(30) NOT NULL,
    `TargetId` VARCHAR(64) NOT NULL,
    `Details` TEXT NOT NULL,
    `CreatedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    INDEX `IX_Audit_Created` (`CreatedAt`),
    INDEX `IX_Audit_Actor` (`ActorUserId`)
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
