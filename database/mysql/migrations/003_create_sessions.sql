/*
  Phish Radar AI - server-side authentication sessions
  Session tokens are generated by the Backend. Only their SHA-256 hashes are
  stored in TokenHash.

  Shared-hosting compatible: relationships are indexed but FOREIGN KEY and
  CHECK clauses are intentionally omitted when REFERENCES is unavailable.
*/

CREATE TABLE IF NOT EXISTS `Sessions`
(
    `SessionId` CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    `UserId` BIGINT UNSIGNED NOT NULL,
    `TokenHash` BINARY(32) NOT NULL,
    `CreatedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    `LastSeenAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    `ExpiresAt` DATETIME(3) NOT NULL,
    `RevokedAt` DATETIME(3) NULL,

    CONSTRAINT `PK_Sessions` PRIMARY KEY (`SessionId`),
    CONSTRAINT `UX_Sessions_TokenHash` UNIQUE (`TokenHash`),
    INDEX `IX_Sessions_User_ExpiresAt` (`UserId`, `ExpiresAt`)
) ENGINE=InnoDB
  DEFAULT CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;
